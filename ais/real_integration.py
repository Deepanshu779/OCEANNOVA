def score_vessel(
    vessel,
    origin_lat,
    origin_lon
):

    track = vessel["track"]

    trajectory_match, closest_distance = (
        trajectory_score(
            track,
            origin_lat,
            origin_lon
        )
    )

    closest_index = min(
        range(len(track)),
        key=lambda i:
        haversine_km(
            track[i][1],
            track[i][2],
            origin_lat,
            origin_lon
        )
    )

    closest_point = track[
        closest_index
    ]

    closest_time = closest_point[0]

    temporal = temporal_score(
        closest_time
    )

    proximity = proximity_score(
        closest_distance
    )

    behavior = vessel[
        "behavior"
    ]

    score = (
        0.35 * proximity
        +
        0.20 * temporal
        +
        0.30 * trajectory_match
        +
        0.15 * behavior
    )

    return {

        "mmsi": vessel["mmsi"],

        "vessel": vessel["name"],

        "attribution_score": round(
            score * 100,
            2
        ),

        "distance_km": round(
            closest_distance,
            3
        ),

        "time_difference_hours": (
            closest_time
        ),

        "proximity_score": round(
            proximity,
            4
        ),

        "temporal_score": round(
            temporal,
            4
        ),

        "trajectory_match_score": round(
            trajectory_match,
            4
        ),

        "behavioral_anomaly_score": round(
            behavior,
            4
        ),

        "relevance": (
            "high"
            if score >= 0.70
            else
            "medium"
            if score >= 0.45
            else
            "low"
        )
    }


