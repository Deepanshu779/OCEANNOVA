EARTH_RADIUS_KM = 6371.0


def haversine_km(
    lat1,
    lon1,
    lat2,
    lon2
):

    lat1 = math.radians(lat1)
    lat2 = math.radians(lat2)

    dlat = lat2 - lat1

    dlon = math.radians(
        lon2
        - lon1
    )

    a = (
        math.sin(dlat / 2) ** 2
        +
        math.cos(lat1)
        * math.cos(lat2)
        * math.sin(dlon / 2) ** 2
    )

    return (
        2
        * EARTH_RADIUS_KM
        * math.asin(
            math.sqrt(a)
        )
    )


def proximity_score(
    distance_km,
    radius_km=50
):

    return max(
        0.0,
        min(
            1.0,
            1.0
            - distance_km
            / radius_km
        )
    )


def temporal_score(
    hours,
    window=12
):

    return max(
        0.0,
        min(
            1.0,
            1.0
            - abs(hours)
            / window
        )
    )


def bearing(
    lat1,
    lon1,
    lat2,
    lon2
):

    lat1 = math.radians(lat1)
    lat2 = math.radians(lat2)

    dlon = math.radians(
        lon2 - lon1
    )

    y = math.sin(dlon) * math.cos(lat2)

    x = (
        math.cos(lat1)
        * math.sin(lat2)
        -
        math.sin(lat1)
        * math.cos(lat2)
        * math.cos(dlon)
    )

    angle = math.degrees(
        math.atan2(y, x)
    )

    return (
        angle + 360
    ) % 360


def trajectory_score(
    track,
    origin_lat,
    origin_lon
):

    distances = []

    for point in track:

        hour = point[0]
        lat = point[1]
        lon = point[2]

        distance = haversine_km(
            lat,
            lon,
            origin_lat,
            origin_lon
        )

        distances.append(
            distance
        )

    closest = min(
        distances
    )

    return max(
        0.0,
        min(
            1.0,
            1.0
            - closest / 50
        )
    ), closest


